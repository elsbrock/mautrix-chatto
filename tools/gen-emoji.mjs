#!/usr/bin/env node
// Generates pkg/emoji/emoji_gen.go from Chatto's own emoji catalogue at the
// release pinned in pkg/chattoclient/client.go (UpstreamVersion):
// - cli/internal/core/emoji_gen.go: every reaction name the server accepts,
//   including Slack-style skin-tone variants such as "thumbsup::skin-tone-4".
// - gemoji plus tools/emoji-additions.json: the order that decides which name
//   Chatto's frontend sends for an emoji (emojiNameFromUnicode in
//   packages/chatto-client/src/messaging/emojiShortcodes.ts).
// The sources are parsed as data; nothing downloaded is executed.
// Usage: node tools/gen-emoji.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const client = readFileSync(resolve(root, 'pkg/chattoclient/client.go'), 'utf8');
const version = client.match(/^const UpstreamVersion = "(.+)"$/m)[1];

async function fetchText(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return res.text();
}
const upstream = (path) =>
  fetchText(`https://raw.githubusercontent.com/chattocorp/chatto/${version}/${path}`);

// Every name the server accepts, with its emoji.
const catalogue = [
  ...(await upstream('cli/internal/core/emoji_gen.go')).matchAll(/^\t"([^"]+)":\s+"([^"]+)",$/gm),
].map((m) => [m[1], m[2]]);
if (catalogue.length < 3000) throw new Error(`catalogue has only ${catalogue.length} names`);

// gemoji's index.js is one array of object literals.
const gemojiVersion = (await upstream('pnpm-lock.yaml')).match(/^ {2}gemoji@(\d+\.\d+\.\d+):$/m)[1];
const gemojiSrc = await fetchText(`https://cdn.jsdelivr.net/npm/gemoji@${gemojiVersion}/index.js`);
const gemoji = [...gemojiSrc.matchAll(/emoji: '([^']+)',\s*names: \[([^\]]*)\]/g)].map((m) => ({
  emoji: m[1],
  names: [...m[2].matchAll(/'([^']+)'/g)].map((n) => n[1]),
}));
if (gemoji.length !== gemojiSrc.split('emoji: ').length - 1) throw new Error('could not parse every gemoji entry');
const additions = JSON.parse(await upstream('tools/emoji-additions.json'));

// The names Chatto's frontend sends, built the way emojiNameFromUnicode is.
const preferred = new Map();
for (const e of [...gemoji, ...additions]) {
  const name = e.names[0] === '+1' || e.names[0] === '-1' ? e.names[1] : e.names[0];
  preferred.set(e.emoji, name);
}
const bases = new Set(preferred.values());
for (const [name, emoji] of catalogue) {
  if (name.includes('::') && bases.has(name.split('::')[0])) preferred.set(emoji, name);
}

// One entry per emoji; the first name is the one Chatto's frontend sends.
const names = new Map();
for (const [name, emoji] of catalogue) {
  if (!names.has(emoji)) names.set(emoji, []);
  names.get(emoji).push(name);
}
const entries = [...names].map(([emoji, list]) => {
  list.sort();
  const first = preferred.get(emoji);
  if (first && list.includes(first)) {
    list.splice(list.indexOf(first), 1);
    list.unshift(first);
  }
  return [emoji, list];
});
entries.sort((a, b) => (a[1][0] < b[1][0] ? -1 : a[1][0] > b[1][0] ? 1 : 0));

const q = (s) => JSON.stringify(s);
const lines = entries.map(([emoji, list]) => `\t{${q(emoji)}, []string{${list.map(q).join(', ')}}},`);
const out = `// Code generated by tools/gen-emoji.mjs from Chatto ${version}. DO NOT EDIT.
// Source: cli/internal/core/emoji_gen.go, gemoji@${gemojiVersion} (MIT) and
// tools/emoji-additions.json in chattocorp/chatto (AGPL-3.0-or-later). The
// skin-tone sequences come from Unicode's emoji-test.txt (Unicode License).

package emoji

// catalogue lists every emoji Chatto accepts as a reaction, sorted by name.
// The first name of an entry is the one Chatto's own frontend sends.
var catalogue = []entry{
${lines.join('\n')}
}
`;
writeFileSync(resolve(root, 'pkg/emoji/emoji_gen.go'), out);
console.log(`wrote ${entries.length} emoji, ${catalogue.length} names (Chatto ${version}, gemoji ${gemojiVersion})`);
