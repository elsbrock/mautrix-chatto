#!/usr/bin/env node
// Generates pkg/emoji/emoji_gen.go from the gemoji dataset, the same source
// Chatto uses for reaction shortcodes (cli/internal/core/emoji_gen.go).
// Usage: node tools/gen-emoji.mjs [gemoji-version]
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const version = process.argv[2] ?? '8.1.0';
const src = await (await fetch(`https://cdn.jsdelivr.net/npm/gemoji@${version}/index.js`)).text();
const { gemoji } = await import('data:text/javascript;base64,' + Buffer.from(src).toString('base64'));

const q = (s) => JSON.stringify(s);
const lines = gemoji.map((e) => `\t{${q(e.emoji)}, []string{${e.names.map(q).join(', ')}}},`);
const out = `// Code generated by tools/gen-emoji.mjs from gemoji@${version}. DO NOT EDIT.

package emoji

// gemojiTable lists every gemoji entry in dataset order. The first name of an
// entry is its canonical shortcode, matching gemoji's emojiToName.
var gemojiTable = []entry{
${lines.join('\n')}
}
`;
const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(resolve(here, '../pkg/emoji/emoji_gen.go'), out);
console.log(`wrote ${gemoji.length} entries`);
